#!/usr/bin/env python3
"""The source-patch inventory: deps/patches/ headers are the source of truth.

    python3 ci/patches.py check           # offline; what tests/preflight.sh runs
    python3 ci/patches.py write           # regenerate the tables in deps/patches/README.md
    python3 ci/patches.py online          # GitHub: which patches can be dropped (run per release pass and per bump)
    python3 ci/patches.py online --only php-8.4 --fail-on-drop

Every patch header carries four single-line fields, anywhere before the first diff line
(`diff --git`, `---` or `Index:`); free text, `Source:` lines and mail headers may sit around them:

    Fixes:     what breaks without it, one line
    Origin:    own | php-src commit <sha> | php-src pull <n> | php-src pull <n> commit <sha>
               (ext-* directories: own | https://github.com/<extension repo>/pull/<n> or /commit/<sha>)
    Upstream:  <status>[: detail], status one of merged open unfixed never n/a
    Drop-when: the condition under which the patch goes away

`check` validates the fields, that every directory names a pinned version
(matrix.json) or a pinned extension tag (php/ext.json), and that the generated
block of deps/patches/README.md is current. It does not apply patches: that
needs the pinned source trees, which are not cheap or offline.

`online` asks GitHub (gh api) about each patch, against the pinned release tag
(matrix.json, php-src; the tag in php/ext.json for extensions):

  * whether the origin commit is an ancestor of the tag, and the origin pull
    request's state;
  * whether the patch still applies to the files at the tag, or the whole patch
    reverses cleanly there (the tag carries the change, cherry-picks and own
    fixes included; a patch applied to only some of its files is a conflict);
  * the same tree test at the head of the upstream branch, as a heads-up that
    the next release will let the patch go.

DROP means the pinned release already carries the change: delete the patch.
REVIEW means a header disagrees with upstream or the patch no longer matches.
"""
import argparse
import functools
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PATCHES = ROOT / "deps" / "patches"
README = PATCHES / "README.md"
MATRIX = ROOT / "matrix.json"
EXT_JSON = ROOT / "php" / "ext.json"

BEGIN = "<!-- patches:begin (generated by ci/patches.py; edit the patch headers, then run `python3 ci/patches.py write`) -->"
END = "<!-- patches:end -->"

FIELDS = ("Fixes", "Origin", "Upstream", "Drop-when")
STATUSES = ("merged", "open", "unfixed", "never", "n/a")
NAME_RE = re.compile(r"^\d{3}-[a-z0-9]+(?:-[a-z0-9]+)*\.patch$")
HEADER_END_RE = re.compile(r"^(diff --git |--- |Index: )")
ORIGIN_RE = re.compile(r"^php-src(?: pull (\d+))?(?: commit ([0-9a-f]{10,40}))?$")
EXT_ORIGIN_RE = re.compile(r"^https://github\.com/([^/\s]+/[^/\s]+)/(?:pull/\d+|commit/[0-9a-f]{10,40})$")
PHP_DIR_RE = re.compile(r"^php-(\d+\.\d+)$")
EXT_DIR_RE = re.compile(r"^ext-([a-z0-9_]+)-(.+)$")
GITHUB_TAG_URL_RE = re.compile(r"^https://github\.com/([^/]+/[^/]+)/archive/refs/tags/(.+)\.tar\.gz$")


class Patch:
    def __init__(self, path):
        self.path = path
        self.name = path.name
        self.component = path.parent.name
        self.rel = f"{self.component}/{self.name}"
        self.text = path.read_text(encoding="utf-8")
        self.fields = {}
        self.problems = []
        self._parse()

    def _parse(self):
        for line in self.text.splitlines():
            if HEADER_END_RE.match(line):
                break
            m = re.match(r"^(Fixes|Origin|Upstream|Drop-when): ?(.*)$", line)
            if not m:
                continue
            key, value = m.group(1), m.group(2).strip()
            if key in self.fields:
                self.problems.append(f"{self.rel}: duplicate {key}: field")
            self.fields[key] = value
        for key in FIELDS:
            if not self.fields.get(key):
                self.problems.append(f"{self.rel}: missing or empty {key}: field")
        if not NAME_RE.match(self.name):
            self.problems.append(f"{self.rel}: file name is not NNN-short-description.patch")
        if "|" in "".join(self.fields.values()):
            self.problems.append(f"{self.rel}: a field contains '|', which breaks the generated table")
        self.pull = self.commit = self.origin_repo = None
        origin = self.fields.get("Origin")
        is_ext = bool(EXT_DIR_RE.match(self.component))
        if origin and origin != "own":
            if is_ext:
                m = EXT_ORIGIN_RE.match(origin)
                if not m:
                    self.problems.append(
                        f"{self.rel}: Origin must be 'own' or a pull request or commit URL in the extension's "
                        f"repository (https://github.com/<repo>/pull/<n> or /commit/<sha>), got {origin!r}"
                    )
                else:
                    self.origin_repo = m.group(1)
            else:
                m = ORIGIN_RE.match(origin)
                if not m or not (m.group(1) or m.group(2)):
                    self.problems.append(
                        f"{self.rel}: Origin must be 'own', 'php-src commit <sha>', 'php-src pull <n>' "
                        f"or 'php-src pull <n> commit <sha>', got {origin!r}"
                    )
                else:
                    self.pull, self.commit = m.group(1), m.group(2)
        upstream = self.fields.get("Upstream")
        if upstream:
            self.status = re.split(r"[: ]", upstream, maxsplit=1)[0]
            if self.status not in STATUSES:
                self.problems.append(f"{self.rel}: Upstream status {self.status!r} is not one of {', '.join(STATUSES)}")
            elif origin:
                if self.status == "open" and not (self.pull or self.origin_repo):
                    self.problems.append(f"{self.rel}: Upstream is open but Origin names no pull request")
                if self.status == "merged" and not (self.pull or self.commit or self.origin_repo):
                    self.problems.append(f"{self.rel}: Upstream is merged but Origin names no commit or pull request")
                if origin == "own" and self.status in ("open", "merged"):
                    self.problems.append(f"{self.rel}: Origin is own but Upstream is {self.status}")
        else:
            self.status = None

    def targets(self):
        return sorted(set(re.findall(r"^--- a/(\S+)", self.text, re.M)))


def php_key(component):
    m = PHP_DIR_RE.match(component)
    return (0, tuple(int(x) for x in m.group(1).split("."))) if m else (1, component)


def load_components():
    matrix = json.loads(MATRIX.read_text())
    ext = json.loads(EXT_JSON.read_text())["extensions"]
    problems = []
    comps = {}
    for d in sorted(p for p in PATCHES.iterdir() if p.is_dir()):
        m = PHP_DIR_RE.match(d.name)
        e = EXT_DIR_RE.match(d.name)
        if m:
            version = m.group(1)
            if version not in matrix["versions"]:
                problems.append(f"{d.name}: matrix.json has no version {version}")
                continue
            info = {
                "kind": "php",
                "title": f"PHP {version}",
                "repo": "php/php-src",
                "pin": f"php-{matrix['versions'][version]['release']}",
                "branch": f"PHP-{version}",
            }
        elif e:
            name, tag = e.groups()
            entry = next((x for x in ext if x.get("name") == name), None)
            m2 = GITHUB_TAG_URL_RE.match(entry.get("url", "")) if entry else None
            if not m2 or m2.group(2) != tag:
                problems.append(f"{d.name}: php/ext.json does not pin {name} at {tag}")
                continue
            info = {
                "kind": "ext",
                "title": f"{name} {tag}",
                "repo": m2.group(1),
                "pin": tag,
                "branch": None,
            }
        else:
            problems.append(f"{d.name}: not php-<version> or ext-<name>-<tag>")
            continue
        info["dir"] = d
        info["patches"] = [Patch(p) for p in sorted(d.glob("*.patch"))]
        for p in info["patches"]:
            if p.origin_repo and p.origin_repo != info["repo"]:
                p.problems.append(f"{p.rel}: Origin repository {p.origin_repo} is not the extension's repository {info['repo']}")
        if not info["patches"]:
            problems.append(f"{d.name}: no patches")
        comps[d.name] = info
    for c in comps.values():
        for p in c["patches"]:
            problems.extend(p.problems)
    ordered = dict(sorted(comps.items(), key=lambda kv: php_key(kv[0])))
    return ordered, problems


def origin_cell(p):
    if p.fields.get("Origin") == "own":
        return "own"
    if p.origin_repo:
        url = p.fields["Origin"]
        return f"[{url.removeprefix('https://github.com/')}]({url})"
    parts = []
    if p.pull:
        parts.append(f"[php-src#{p.pull}](https://github.com/php/php-src/pull/{p.pull})")
    if p.commit:
        parts.append(f"[`{p.commit}`](https://github.com/php/php-src/commit/{p.commit})")
    return ", ".join(parts)


def render(comps):
    out = [BEGIN, ""]
    for c in comps.values():
        out += [f"### {c['title']}", "", "| Patch | Fixes | Origin | Upstream | Drop when |", "|---|---|---|---|---|"]
        for p in c["patches"]:
            f = p.fields
            out.append(
                f"| `{p.name.removesuffix('.patch')}` | {f['Fixes']} | {origin_cell(p)} | {f['Upstream']} | {f['Drop-when']} |"
            )
        out.append("")
    out.append(END)
    return "\n".join(out)


def splice(readme, block):
    i, j = readme.find(BEGIN), readme.find(END)
    if i < 0 or j < i:
        return None
    return readme[:i] + block + readme[j + len(END):]


def cmd_check(_args):
    comps, problems = load_components()
    if not problems:
        want = splice(README.read_text(encoding="utf-8"), render(comps))
        if want is None:
            problems.append(f"{README.relative_to(ROOT)}: generated block markers not found")
        elif want != README.read_text(encoding="utf-8"):
            problems.append(f"{README.relative_to(ROOT)} is stale -- run: python3 ci/patches.py write")
    for p in problems:
        print(f"PROBLEM: {p}", file=sys.stderr)
    if problems:
        return 1
    n = sum(len(c["patches"]) for c in comps.values())
    print(f"{n} patches in {len(comps)} components: headers valid, {README.relative_to(ROOT)} current")
    return 0


def cmd_write(_args):
    comps, problems = load_components()
    for p in problems:
        print(f"PROBLEM: {p}", file=sys.stderr)
    if problems:
        return 1
    text = README.read_text(encoding="utf-8")
    new = splice(text, render(comps))
    if new is None:
        print(f"{README.relative_to(ROOT)}: generated block markers not found", file=sys.stderr)
        return 1
    if new != text:
        README.write_text(new, encoding="utf-8")
        print(f"updated {README.relative_to(ROOT)}")
    else:
        print(f"{README.relative_to(ROOT)} already current")
    return 0


# ---------------------------------------------------------------- online

class GhError(Exception):
    pass


class ToolError(Exception):
    pass


def run(cmd, timeout=60, **kw):
    """subprocess.run with the C locale, a timeout, and a ToolError instead of a traceback when the binary is
    missing or hangs."""
    env = {**os.environ, "LC_ALL": "C"}
    try:
        return subprocess.run(cmd, capture_output=True, env=env, timeout=timeout, **kw)
    except FileNotFoundError:
        raise ToolError(f"{cmd[0]} not found in PATH; it is required for `online`") from None
    except subprocess.TimeoutExpired:
        raise ToolError(f"{' '.join(cmd[:3])} timed out after {timeout}s") from None


@functools.lru_cache(maxsize=None)
def gh(path, raw=False):
    cmd = ["gh", "api", path]
    if raw:
        cmd += ["-H", "Accept: application/vnd.github.raw"]
    r = run(cmd)
    if r.returncode != 0:
        raise GhError(r.stderr.decode(errors="replace").strip().splitlines()[0] if r.stderr else f"gh api {path} failed")
    return r.stdout


def gh_json(path):
    return json.loads(gh(path))


def compare_status(repo, base, head):
    """'behind' or 'identical' = head is an ancestor of (or equal to) base."""
    try:
        return gh_json(f"repos/{repo}/compare/{base}...{head}")["status"]
    except GhError as e:
        return f"error ({e})"


def tree_state(patch, repo, ref):
    """needed | upstream-has-it | conflict | error (...): a zero-fuzz forward dry run of the patch on the files at ref,
    the way the build applies it. If that fails, upstream-has-it only when the whole patch reverses cleanly and
    re-applies to the result (every file already carries the change); a partly applied patch is a conflict."""
    with tempfile.TemporaryDirectory(prefix="patches-") as tmp:
        tmpdir = Path(tmp)
        for target in patch.targets():
            try:
                data = gh(f"repos/{repo}/contents/{target}?ref={ref}", raw=True)
            except GhError as e:
                return f"error ({target}: {e})"
            dest = tmpdir / target
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)

        base = ["patch", "-p1", "--batch", "--fuzz=0", "-d", str(tmpdir), "-i", str(patch.path)]
        if run(base + ["--forward", "--dry-run"]).returncode == 0:
            return "needed"
        # --batch makes patch drop -R with "Unreversed patch detected" and apply the patch forward instead, so
        # a clean -R exit proves nothing: reverse for real (the tree is a throwaway), then the forward patch
        # must apply again to the result.
        if run(base + ["-R"]).returncode == 0 and run(base + ["--forward", "--dry-run"]).returncode == 0:
            return "upstream-has-it"
    return "conflict"


def check_patch(c, p):
    repo, pin, branch = c["repo"], c["pin"], c["branch"]
    notes, drop, review = [], [], []

    pin_tree = tree_state(p, repo, pin)
    notes.append(f"{pin}: {pin_tree}")
    if pin_tree == "upstream-has-it":
        drop.append(f"{pin} already carries the change (the whole patch reverses cleanly)")
    elif pin_tree == "conflict":
        review.append(f"does not apply to {pin} and is not applied there")
    elif pin_tree.startswith("error"):
        review.append(pin_tree)

    if p.commit:
        st = compare_status(repo, pin, p.commit)
        notes.append(f"commit {p.commit[:10]}: {'in ' + pin if st in ('behind', 'identical') else st}")
        if st in ("behind", "identical"):
            drop.append(f"commit {p.commit[:10]} is an ancestor of {pin}")
        elif st.startswith("error"):
            review.append(f"commit {p.commit[:10]}: {st}")

    if p.pull:
        try:
            pr = gh_json(f"repos/php/php-src/pulls/{p.pull}")
        except GhError as e:
            review.append(f"PR #{p.pull}: {e}")
        else:
            state = "merged" if pr["merged"] else pr["state"]
            notes.append(f"PR #{p.pull}: {state} (base {pr['base']['ref']})")
            if pr["merged"]:
                st = compare_status("php/php-src", pin, pr["merge_commit_sha"])
                if st in ("behind", "identical"):
                    drop.append(f"PR #{p.pull} merged and its merge commit is in {pin}")
                elif p.status == "merged":
                    notes.append(f"PR #{p.pull}: merged, not yet in {pin} (header says merged)")
                else:
                    review.append(f"PR #{p.pull} is merged (into {pr['base']['ref']}) but {pin} does not contain it yet; header says {p.status!r}")
            elif pr["state"] == "closed":
                review.append(f"PR #{p.pull} was closed without merging")
            elif p.status != "open":
                review.append(f"PR #{p.pull} is open but the header says {p.status!r}")
            if p.commit and not pr["head"]["sha"].startswith(p.commit):
                notes.append(f"heads-up: PR #{p.pull} head is now {pr['head']['sha'][:10]}, the patch carries {p.commit[:10]}")

    if p.status == "open" and not (p.pull or p.origin_repo):
        review.append("status open without a pull request")

    if branch is None:
        try:
            branch = gh_json(f"repos/{repo}")["default_branch"]
        except GhError as e:
            branch = None
            notes.append(f"default branch: error ({e})")
    if branch:
        head_tree = tree_state(p, repo, branch)
        notes.append(f"{branch} head: {head_tree}")
        if head_tree == "upstream-has-it" and pin_tree == "needed":
            notes.append(f"heads-up: {branch} has it, so the next release drops this patch")
        elif head_tree == "conflict" and pin_tree == "needed":
            notes.append(f"heads-up: the patch no longer applies to {branch} head; expect a rewrite at the next bump")

    verdict = "DROP" if drop else "REVIEW" if review else "KEEP"
    return verdict, notes, drop + review


def cmd_online(args):
    if run(["gh", "auth", "status", "--hostname", "github.com"]).returncode != 0:
        print("gh is not authenticated for github.com (gh auth login)", file=sys.stderr)
        return 1
    if run(["patch", "--version"]).returncode != 0:
        print("patch does not run", file=sys.stderr)
        return 1
    comps, problems = load_components()
    for p in problems:
        print(f"PROBLEM: {p}", file=sys.stderr)
    if problems:
        return 1
    if args.only and not any(args.only in name for name in comps):
        print(f"--only {args.only!r} matches no patch directory ({', '.join(comps)})", file=sys.stderr)
        return 1
    drops = reviews = 0
    for name, c in comps.items():
        if args.only and args.only not in name:
            continue
        print(f"== {name} (pin {c['pin']})")
        for p in c["patches"]:
            verdict, notes, why = check_patch(c, p)
            drops += verdict == "DROP"
            reviews += verdict == "REVIEW"
            print(f"{verdict:6} {p.name}")
            for n in notes:
                print(f"         {n}")
            for w in why:
                print(f"         -> {w}")
    print(f"\n{drops} patch(es) can be dropped, {reviews} need review")
    return 1 if args.fail_on_drop and drops else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check", help="offline header and README check").set_defaults(fn=cmd_check)
    sub.add_parser("write", help="regenerate the README tables").set_defaults(fn=cmd_write)
    o = sub.add_parser("online", help="ask GitHub which patches can be dropped")
    o.add_argument("--only", help="substring of a patch directory name, e.g. php-8.4")
    o.add_argument("--fail-on-drop", action="store_true", help="exit 1 when a patch can be dropped")
    o.set_defaults(fn=cmd_online)
    args = ap.parse_args(argv)
    try:
        return args.fn(args)
    except ToolError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
